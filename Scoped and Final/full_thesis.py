    if len(matches) > 1:
        print(f"\nWARNING: Multiple copies found for {filename}:")
        for match in matches:
            print("  ", match)

        # Prefer the copy directly under BASE_DIR if present
        direct = BASE_DIR / filename
        if direct.exists():
            return direct

    return matches[0]


