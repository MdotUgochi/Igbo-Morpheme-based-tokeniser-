def build_hf_tokenizer(
    vocab_path,
    merges_path,
    output_path
):

    vocab_path = Path(vocab_path)
    merges_path = Path(merges_path)
    output_path = Path(output_path)

    # --------------------------------------------------------
    # Load vocabulary
    # --------------------------------------------------------

    with open(
        vocab_path,
        "r",
        encoding="utf-8"
    ) as f:

        vocab = json.load(f)

    # --------------------------------------------------------
    # Load merges
    # --------------------------------------------------------

    merges = []

    with open(
        merges_path,
        "r",
        encoding="utf-8"
    ) as f:

        for line_number, raw_line in enumerate(
            f,
            start=1
        ):

            line = raw_line.rstrip("\r\n")

            if not line:
                continue

            if line.startswith("#version:"):
                continue

            parts = line.split()

            if len(parts) != 2:
                raise ValueError(
                    f"Invalid merge at line "
                    f"{line_number}: {repr(line)}"
                )

            merges.append(
                (parts[0], parts[1])
            )

    # --------------------------------------------------------
    # Construct BPE model
    # --------------------------------------------------------

    bpe_model = BPE(
        vocab=vocab,
        merges=merges,
        unk_token="<unk>"
    )

    tokenizer = Tokenizer(
        bpe_model
    )

    # --------------------------------------------------------
    # Pre-tokenization
    #
    # We use whitespace splitting for ordinary downstream
    # text. Morphological boundaries are NOT supplied here.
    #
    # This is intentional:
    # the learned tokenizer must operate on ordinary surface
    # text during inference.
    # --------------------------------------------------------

    tokenizer.pre_tokenizer = Whitespace()

    # --------------------------------------------------------
    # Register special tokens
    # --------------------------------------------------------

    tokenizer.add_special_tokens(
        [
            token
            for token in SPECIAL_TOKENS
            if token in vocab
        ]
    )

    # --------------------------------------------------------
    # Save tokenizer.json
    # --------------------------------------------------------

    tokenizer.save(
        str(output_path)
    )

    return tokenizer


